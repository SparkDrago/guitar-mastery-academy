function playChord(pcs: number[], rootPc: number, at = 0, arpeggiate = false) {
  const c = getContext();
  const t = c.currentTime + 0.03 + at;
  const root = 48 + rootPc;
  let prev = root;
  pcs.forEach((pc, i) => {
    let m = 48 + pc;
    while (m < prev) m += 12;
    if (i === 0) m = root;
    prev = m;
    pluck(m, t + (arpeggiate ? i * 0.12 : i * 0.015), 1.4, 0.5);
  });
}

export function TheoryPage() {
  useDocumentTitle('Theory Academy');
  const { query } = useLocation();
  const qTab = query.get('tab');
  const [tab, setTab] = useState<'keys' | 'intervals' | 'glossary'>(qTab === 'glossary' || qTab === 'intervals' ? qTab : 'keys');
  useEffect(() => { if (qTab === 'glossary' || qTab === 'intervals' || qTab === 'keys') setTab(qTab); }, [qTab, query.get('q')]);
  const theoryLessons = LESSONS.filter((l) => l.categories.includes('theory'));
  return (
    <div>
      <PageHeader eyebrow="Learn" title="Theory Academy" subtitle="Reference tools for keys, harmony and intervals. Every chart is generated by the same theory engine the lessons and tools use."
        actions={<Segmented value={tab} onChange={setTab} aria-label="Section" options={[{ value: 'keys', label: 'Keys & harmony' }, { value: 'intervals', label: 'Intervals' }, { value: 'glossary', label: 'Glossary' }]} />} />
      {tab === 'keys' && <KeysSection />}
      {tab === 'intervals' && <IntervalsSection />}
      {tab === 'glossary' && <GlossarySection key={query.get('q') ?? ''} initial={query.get('q') ?? ''} />}
      <Card className="mt-5" title="Theory lessons" subtitle={`${theoryLessons.length} lessons in the curriculum`}>
        <ul className="grid gap-1.5 sm:grid-cols-2 lg:grid-cols-3">
          {theoryLessons.map((l) => <li key={l.id}><Link to={`/lessons/${l.id}`} className="flex items-center gap-2 rounded-lg px-2 py-1.5 text-sm text-ink-200 hover:bg-ink-800"><LuBookOpen size={14} className="text-ink-400" /><span className="truncate">L{l.level} · {l.title}</span></Link></li>)}
        </ul>
      </Card>
    </div>
  );
}

function KeysSection() {
  const [sel, setSel] = useState(0);
  const [minor, setMinor] = useState(false);
  const [sevenths, setSevenths] = useState(false);
  const k = CIRCLE_OF_FIFTHS[sel];
  const tonic = minor ? k.minor.replace('m', '') : k.major;
  const sig = keySignature(tonic, minor ? 'minor' : 'major');
  const scale = buildScale(tonic, minor ? 'aeolian' : 'major');
  const chords = useMemo(() => diatonicChords(tonic, minor ? 'aeolian' : 'major', sevenths), [tonic, minor, sevenths]);
  const R = 150, r = 100, cx0 = 180, cy0 = 180;
  const pt = (i: number, rad: number) => [cx0 + rad * Math.sin((i * Math.PI) / 6), cy0 - rad * Math.cos((i * Math.PI) / 6)];
  const neighbours = [(sel + 11) % 12, (sel + 1) % 12];

  return (
    <div className="grid gap-5 lg:grid-cols-[380px_1fr]">
      <Card title="Circle of fifths" subtitle="Clockwise adds a sharp; anticlockwise adds a flat. Click a key.">
        <svg viewBox="0 0 360 360" className="mx-auto w-full max-w-[360px]" role="group" aria-label="Circle of fifths" data-testid="circle-of-fifths">
          <circle cx={cx0} cy={cy0} r={R + 24} className="svg-surface-2" style={{ stroke: 'var(--color-ink-700)' }} />
          <circle cx={cx0} cy={cy0} r={(R + r) / 2 - 2} fill="none" style={{ stroke: 'var(--color-ink-700)' }} />
          {CIRCLE_OF_FIFTHS.map((key, i) => {
            const [x, y] = pt(i, R);
            const [x2, y2] = pt(i, r - 12);
            const active = i === sel;
            const near = neighbours.includes(i);
            return (
              <g key={key.major} onClick={() => setSel(i)} className="cursor-pointer" role="button" aria-label={`${key.major} major / ${key.minor}`} aria-pressed={active}>
                <circle cx={x} cy={y} r={22} style={{ fill: active && !minor ? 'var(--color-accent-500)' : near ? 'var(--color-ink-700)' : 'var(--color-ink-850)', stroke: active ? 'var(--color-accent-300)' : 'var(--color-ink-600)' }} />
                <text x={x} y={y + 5} textAnchor="middle" fontSize="15" fontWeight="600" style={{ fill: active && !minor ? '#fff' : 'var(--color-ink-100)' }}>{key.major}</text>
                <circle cx={x2} cy={y2} r={17} style={{ fill: active && minor ? 'var(--color-accent-500)' : 'var(--color-ink-900)', stroke: active ? 'var(--color-accent-300)' : 'var(--color-ink-700)' }} />
                <text x={x2} y={y2 + 4} textAnchor="middle" fontSize="11.5" style={{ fill: active && minor ? '#fff' : 'var(--color-ink-300)' }}>{key.minor}</text>
              </g>
            );
          })}
          <text x={cx0} y={cy0 - 4} textAnchor="middle" fontSize="13" className="svg-text" fontWeight="600">{tonic} {minor ? 'minor' : 'major'}</text>
          <text x={cx0} y={cy0 + 14} textAnchor="middle" fontSize="11" className="svg-axis">{sig.sharps ? `${sig.sharps} sharp${sig.sharps > 1 ? 's' : ''}` : sig.flats ? `${sig.flats} flat${sig.flats > 1 ? 's' : ''}` : 'no sharps or flats'}</text>
        </svg>
        <div className="mt-3 flex justify-center"><Segmented size="sm" value={minor ? 'minor' : 'major'} onChange={(v) => setMinor(v === 'minor')} options={[{ value: 'major', label: 'Major' }, { value: 'minor', label: 'Relative minor' }]} aria-label="Key quality" /></div>
      </Card>
      <div className="space-y-5">
        <Card title={`${tonic} ${minor ? 'natural minor' : 'major'}`} subtitle={`Relative ${minor ? 'major' : 'minor'}: ${minor ? k.major : noteName(relativeMinor(parseNote(k.major)!))} · neighbours: ${CIRCLE_OF_FIFTHS[neighbours[0]].major} and ${CIRCLE_OF_FIFTHS[neighbours[1]].major}`} data-testid="key-info">
          <div className="flex flex-wrap items-center gap-2">
            {scale.notes.map((n, i) => <Badge key={i} tone={i === 0 ? 'accent' : 'neutral'}>{noteName(n, true)} <span className="text-ink-400">{scale.tokens[i]}</span></Badge>)}
            <button type="button" className="ml-1 inline-flex items-center gap-1 text-xs text-accent-300 hover:underline" onClick={() => { const c = getContext(); const t = c.currentTime + 0.05; let prev = 51; scale.notes.concat([scale.notes[0]]).forEach((n, i) => { let m = 48 + pcOf(n); while (m <= prev) m += 12; prev = m; pluck(m, t + i * 0.32, 0.4, 0.6); }); }}><LuVolume2 size={13} /> Hear the scale</button>
          </div>
          <p className="mt-2 text-xs text-ink-400">Key signature: {sig.accidentals.length ? sig.accidentals.join(' ') : 'none'}.</p>
        </Card>
        <Card title="Diatonic chords" action={<Toggle checked={sevenths} onChange={setSevenths} label="Sevenths" />} subtitle="Built by stacking thirds on each scale degree. Click to hear.">
          <div className="grid grid-cols-2 gap-2 sm:grid-cols-4 xl:grid-cols-7" data-testid="diatonic-chords">
            {chords.map((d) => (
              <button key={d.degree} type="button" onClick={() => playChord(d.chord.pcs, pcOf(d.chord.root))} className="rounded-lg border border-ink-700 bg-ink-900/60 px-2 py-2 text-left hover:border-ink-500">
                <div className="text-xs text-accent-300">{d.numeral}</div>
                <div className="font-semibold text-ink-50">{d.chord.symbol}</div>
                <div className="text-[11px] text-ink-400">{d.chord.notes.map((n) => noteName(n, true)).join(' ')}</div>
                <div className={cx('mt-1 text-[10px] uppercase tracking-wide', d.function === 'tonic' ? 'text-ok-400' : d.function === 'dominant' ? 'text-warn-400' : 'text-cyan-400')}>{d.function}</div>
              </button>
            ))}
          </div>
          <p className="mt-3 text-xs text-ink-400">Numerals follow the rock/pop convention used throughout the app: always measured from the major scale of the tonic, so minor keys read i, ii°, ♭III, iv, v, ♭VI, ♭VII.</p>
        </Card>
        <Card title="Common progressions in this key">
          <ul className="space-y-1.5 text-sm">
            {(minor ? [[0, 5, 6, 0], [0, 3, 4, 0], [0, 6, 5, 4]] : [[0, 4, 5, 3], [0, 5, 3, 4], [1, 4, 0, 0], [0, 3, 4, 3]]).map((p) => (
              <li key={p.join()} className="flex items-center gap-3">
                <button type="button" className="rounded p-1 text-accent-300 hover:bg-ink-800" onClick={() => p.forEach((d, i) => playChord(chords[d].chord.pcs, pcOf(chords[d].chord.root), i * 0.9))} aria-label="Play progression"><LuVolume2 size={14} /></button>
                <span className="font-mono text-ink-400">{p.map((d) => chords[d].numeral).join(' – ')}</span>
                <span className="text-ink-100">{p.map((d) => chords[d].chord.symbol).join(' – ')}</span>
              </li>
            ))}
          </ul>
          <p className="mt-3 text-xs text-ink-400">Try any of these in the <Link to="/jam" className="text-accent-300 hover:underline">Jam Room</Link>.</p>
        </Card>
      </div>
    </div>
  );
}

function IntervalsSection() {
  const tuning = useActiveTuning();
  const s = useStudent();
  const [root, setRoot] = useState(tuning.strings[1] + 3);
  const [sel, setSel] = useState(7);
  const play = (semis: number, harmonic: boolean) => {
    const c = getContext();
    const t = c.currentTime + 0.05;
    pluck(root, t, 1.2, 0.6);
    pluck(root + semis, harmonic ? t : t + 0.55, 1.2, 0.6);
  };
  const rootPos = positionsOfMidi(tuning, root, 15)[0];
  const targetPositions = positionsOfMidi(tuning, root + sel, 15);
  return (
    <div className="grid gap-5 lg:grid-cols-[1fr_1fr]">
      <Card title="Interval reference" subtitle="Distance in half steps (frets) between two notes. Play them melodically or together.">
        <table className="w-full text-sm" data-testid="interval-table">
          <thead><tr className="text-left text-xs text-ink-400"><th className="py-1.5 font-medium">Half steps</th><th className="font-medium">Name</th><th className="font-medium">Symbol</th><th className="font-medium">Hear</th></tr></thead>
          <tbody>
            {SEMITONE_INTERVALS.map((iv) => (
              <tr key={iv.semitones} className={cx('cursor-pointer border-t border-ink-800', sel === iv.semitones && 'bg-accent-500/10')} onClick={() => setSel(iv.semitones)}>
                <td className="py-1.5 tabular-nums text-ink-300">{iv.semitones}</td>
                <td className="text-ink-100">{iv.name}</td>
                <td className="font-mono text-ink-300">{iv.short}</td>
                <td className="whitespace-nowrap">
                  <button type="button" className="mr-1 rounded px-1.5 py-0.5 text-xs text-accent-300 hover:bg-ink-800" onClick={(e) => { e.stopPropagation(); setSel(iv.semitones); play(iv.semitones, false); }}>melodic</button>
                  <button type="button" className="rounded px-1.5 py-0.5 text-xs text-accent-300 hover:bg-ink-800" onClick={(e) => { e.stopPropagation(); setSel(iv.semitones); play(iv.semitones, true); }}>together</button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </Card>
      <Card title="On the fretboard" subtitle={`Root ${pcName(root % 12, s.profile.noteNames === 'flats')} (purple). Every place the ${SEMITONE_INTERVALS[sel].name.toLowerCase()} above it can be played is marked. Click a fret to move the root.`}>
        <Fretboard tuning={tuning} maxFret={15} leftHanded={s.profile.leftHanded}
          marks={[...(rootPos ? [{ string: rootPos.string, fret: rootPos.fret, tone: 'root' as const, label: 'R' }] : []), ...targetPositions.map((p) => ({ string: p.string, fret: p.fret, tone: 'target' as const, label: SEMITONE_INTERVALS[sel].short }))]}
          onPick={(p) => { setRoot(tuning.strings[p.string] + p.fret); }} testId="interval-fretboard" />
        <p className="mt-3 text-sm text-ink-300">Shapes repeat across string pairs except where the pair includes the G–B strings (in standard tuning), where the upper note moves up one fret, because those strings are a major 3rd apart instead of a 4th.</p>
      </Card>
    </div>
  );
}

function GlossarySection({ initial = '' }: { initial?: string }) {
  const [q, setQ] = useState(initial);
  const [cat, setCat] = useState<'all' | (typeof GLOSSARY)[number]['category']>('all');
  const list = GLOSSARY.filter((g) => (cat === 'all' || g.category === cat) && (!q || `${g.term} ${g.definition}`.toLowerCase().includes(q.toLowerCase())));
  return (
    <Card title="Glossary" subtitle={`${GLOSSARY.length} terms`}>
      <div className="mb-4 flex flex-wrap gap-2">
        <div className="relative min-w-60 flex-1"><LuSearch size={14} className="pointer-events-none absolute left-2.5 top-2.5 text-ink-400" /><input className="input pl-8" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Search terms" aria-label="Search glossary" data-testid="glossary-search" /></div>
        <Segmented size="sm" value={cat} onChange={setCat} aria-label="Category" options={[{ value: 'all', label: 'All' }, { value: 'technique', label: 'Technique' }, { value: 'theory', label: 'Theory' }, { value: 'rhythm', label: 'Rhythm' }, { value: 'notation', label: 'Notation' }, { value: 'equipment', label: 'Gear' }, { value: 'general', label: 'General' }]} />
      </div>
      <dl className="grid gap-x-6 gap-y-3 md:grid-cols-2" data-testid="glossary-list">
        {list.map((g) => (
          <div key={g.term} className="border-b border-ink-800 pb-3">
            <dt className="flex items-center gap-2 font-medium text-ink-50">{g.term} <span className="text-[10px] uppercase tracking-wide text-ink-500">{g.category}</span></dt>
            <dd className="mt-0.5 text-sm text-ink-300">{g.definition} {g.lesson && LESSONS.some((l) => l.id === g.lesson) && <Link to={`/lessons/${g.lesson}`} className="text-xs text-accent-300 hover:underline">Lesson →</Link>}</dd>
          </div>
        ))}
        {list.length === 0 && <p className="text-sm text-ink-400">No terms match.</p>}
      </dl>
    </Card>
  );
}
